"""Small workflows with injected provider/model seams for offline verification."""

from datetime import datetime, timezone
from email.message import EmailMessage
from email import policy
from email.utils import parseaddr, getaddresses
from urllib.parse import quote
import time

from .contracts import Draft, MailError
from .state import MailState


def source_link(account, message_id):
    # authuser chooses the configured account; ID comes from Gmail, never the model.
    return f"https://mail.google.com/mail/?authuser={quote(account, safe='')}#all/{message_id}"


def digest(store, cfg, api, model, start, end):
    now = int(store.clock())
    if (
        type(start) is not int
        or type(end) is not int
        or not 0 <= start < end <= now
        or end - start > 31 * 86400
    ):
        raise MailError("invalid_interval_max_31_days_no_future")
    state = MailState(store)
    key, existing = state.begin(cfg.account, start, end)
    if existing:
        return {
            "job_id": key,
            "run_id": existing,
            "replayed": True,
            "result_retained": store.get_run(existing) is not None,
        }
    started = time.monotonic()
    try:
        api.check_account(cfg.account)
        messages = api.collect(start, end, cfg.max_messages)
        sources = []
        for message in messages:
            if time.monotonic() - started > 600:
                raise MailError("digest_time_budget_exceeded")
            if message.truncated:
                raise MailError(
                    "message_body_truncated_narrow_scope_or_review_manually"
                )
            sources.append((message, model.summarize(message)))
        lines = [
            "ملخص آلي للمراجعة — لا يُنفّذ أي إجراء.",
            f"الفترة UTC: {datetime.fromtimestamp(start, timezone.utc).isoformat()} → {datetime.fromtimestamp(end, timezone.utc).isoformat()}",
            f"الرسائل: {len(messages)} — يشمل المؤرشف؛ يستبعد المرسل والمسودات والسبام والمحذوف.",
            "المرفقات غير مقروءة؛ تغطية الرسائل المتاحة أثناء الجلب، وليست لقطة تاريخية ثابتة.",
        ]
        for message, insight in sources:
            lines += [
                f"\n[{insight.category}] {insight.summary}",
                f"اقتراح: {insight.suggested_action or 'لا يوجد'}",
                source_link(cfg.account, message.id),
            ]
            if message.attachment_count:
                lines.append(f"تنبيه: {message.attachment_count} مرفق غير مقروء.")
        if not messages:
            lines.append("لا توجد رسائل مطابقة في الفترة المحددة.")
        body = "\n".join(lines)
        if len(body) > 12000:
            raise MailError("digest_output_budget_exceeded_narrow_interval")
        run = state.complete(key, cfg.account, start, end, body, sources)
        return {"job_id": key, "run_id": run, "count": len(messages), "replayed": False}
    except Exception as exc:
        code = str(exc) if isinstance(exc, MailError) else "digest_failed"
        state.fail(key, code)
        raise MailError(code) from None


def reply_draft(store, cfg, api, model, mid, instruction):
    if not 1 <= len(instruction.strip()) <= 2000:
        raise MailError("owner_instruction_required_max_2000")
    message = api.get(mid)
    if message.truncated or not message.rfc_id:
        raise MailError("reply_source_incomplete")
    # Recipient is determined from native headers, not generated by the model.
    recipients = getaddresses([message.reply_to or message.sender])
    if len(recipients) != 1:
        raise MailError("ambiguous_reply_recipient")
    recipient = recipients[0][1]
    draft = Draft(
        recipient=recipient,
        subject=message.subject,
        body=model.draft_reply(message, instruction),
        thread_id=message.thread_id,
        in_reply_to=message.rfc_id,
    )
    return MailState(store).new_draft(cfg.account, draft)


def wire_message(account, draft, rfc_id):
    message = EmailMessage(policy=policy.SMTP)
    message["From"] = account
    message["To"] = draft.recipient
    message["Subject"] = draft.subject
    message["Message-ID"] = rfc_id
    if draft.in_reply_to:
        message["In-Reply-To"] = draft.in_reply_to
        message["References"] = draft.in_reply_to
    message.set_content(draft.body)
    return message.as_bytes()


def matches(sent, row):
    draft = Draft.model_validate_json(row["payload"])
    return (
        "SENT" in sent.labels
        and sent.rfc_id == row["rfc_id"]
        and parseaddr(sent.sender)[1].casefold() == row["account"].casefold()
        and [a.casefold() for _, a in getaddresses([sent.recipient])]
        == [draft.recipient.casefold()]
        and not sent.cc
        and not sent.bcc
        and sent.subject == draft.subject
        and sent.body.strip() == draft.body.strip()
        and not sent.truncated
    )


def send_reviewed(store, cfg, api, key, approval_digest):
    if not cfg.send_enabled:
        raise MailError("sending_disabled")
    state = MailState(store)
    row = state.draft(key)
    draft = Draft.model_validate_json(row["payload"])
    api.check_account(cfg.account)
    raw = wire_message(cfg.account, draft, row["rfc_id"])
    state.pending(key, cfg.account, approval_digest, raw)
    # From this point every failure is ambiguous. No retry/reset-to-draft path.
    try:
        receipt = api.send(raw, draft.thread_id)
        provider_id = receipt["id"]
        state.receipt(key, provider_id, False)
        native = api.get(provider_id)
        if not matches(native, row):
            raise MailError("sent_content_not_verified")
        state.receipt(key, provider_id, True)
        return {"id": key, "status": "sent_verified", "provider_id": provider_id}
    except Exception:
        raise MailError("send_needs_reconciliation_do_not_resend") from None


def reconcile(store, cfg, api, key):
    state = MailState(store)
    row = state.draft(key)
    if row["account"] != cfg.account.casefold():
        raise MailError("wrong_draft_account")
    if row["status"] == "sent_verified":
        return {"id": key, "status": "sent_verified", "provider_id": row["provider_id"]}
    if row["status"] not in {"needs_reconciliation", "accepted_unverified"}:
        raise MailError("draft_has_no_send_attempt")
    api.check_account(cfg.account)
    ids = api.ids(f"in:sent rfc822msgid:{row['rfc_id']}", 2)
    if len(ids) != 1 or not matches(api.get(ids[0]), row):
        raise MailError("send_still_uncertain_manual_native_review_required")
    state.receipt(key, ids[0], True)
    return {"id": key, "status": "sent_verified", "provider_id": ids[0]}


def search(api, query, limit):
    if not 1 <= len(query) <= 1000 or not 1 <= limit <= 100:
        raise MailError("invalid_search_bounds")
    return [api.get(mid).model_dump(exclude={"body"}) for mid in api.ids(query, limit)]


def followup(api, mid):
    message = api.get(mid)
    thread = api.call(
        api.service.users()
        .threads()
        .get(userId="me", id=message.thread_id, format="minimal")
    )
    rows = thread.get("messages", [])
    if not rows or len(rows) > 100:
        raise MailError("thread_budget_or_empty")
    messages = [
        api.get(r["id"])
        for r in rows
        if not set(r.get("labelIds", [])) & {"DRAFT", "TRASH", "SPAM"}
    ]
    if not messages:
        raise MailError("no_visible_thread_messages")
    latest = max(messages, key=lambda m: (m.received_ms, m.id))
    return {
        "thread_id": message.thread_id,
        "latest_message_id": latest.id,
        "observed_state": "last_message_sent_by_you"
        if "SENT" in latest.labels
        else "last_message_received",
        "reply_required": "unknown_owner_decision",
        "checked_messages": len(messages),
        "note": "Not a promise that a reply is required; no future monitoring without another check.",
    }
